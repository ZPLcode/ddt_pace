"""Generate the hardware side guard's mesh envelopes and FK from the D1 URDF.

The compiled collector needs no Python, URDF, or mesh files at runtime.
Joint origins/axes are generated alongside the meshes to prevent mixing assets.
"""

from __future__ import annotations

import argparse
import hashlib
import itertools
from pathlib import Path
from xml.etree import ElementTree as ET

import numpy as np
import trimesh
from scipy.spatial.transform import Rotation

PROJECT_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_URDF = PROJECT_ROOT / "assets/d1/robot.urdf"
DEFAULT_OUTPUT = Path(__file__).with_name("d1_side_guard_meshes.hpp")
LEGS = ("FL", "FR", "RL", "RR")
PARTS = ("hip", "thigh", "calf", "foot")


def transform(origin):
    frame = np.eye(4)
    if origin is not None:
        frame[:3, :3] = Rotation.from_euler("xyz", np.fromstring(origin.get("rpy", "0 0 0"), sep=" ")).as_matrix()
        frame[:3, 3] = np.fromstring(origin.get("xyz", "0 0 0"), sep=" ")
    return frame


def mesh_path(urdf, root, leg, part):
    link = root.find(f"link[@name='{leg}_{part}']")
    uri = link.find("visual/geometry/mesh").get("filename")
    if uri.startswith("package://"):
        raise ValueError("Use a URDF with mesh paths relative to the URDF file")
    return (urdf.parent / uri).resolve()


def link_vertices(urdf, root, leg, part):
    link = root.find(f"link[@name='{leg}_{part}']")
    if len(link.findall("visual")) != 1:
        raise ValueError("Expected one visual mesh per leg link")
    vis = link.find("visual")
    mesh = trimesh.load(mesh_path(urdf, root, leg, part), force="mesh")
    scale = np.fromstring(vis.find("geometry/mesh").get("scale", "1 1 1"), sep=" ")
    frame = transform(vis.find("origin"))
    return (mesh.vertices * scale) @ frame[:3, :3].T + frame[:3, 3]


def wheel_bounds(vertices, axis):
    axial = vertices @ axis
    radial = np.linalg.norm(vertices - axial[:, None] * axis, axis=1)
    return np.floor(axial.min() * 1e9) / 1e9, np.ceil(axial.max() * 1e9) / 1e9, np.ceil(radial.max() * 1e9) / 1e9


def fixed_base_frame(root, link_name):
    """Resolve the fixed joints between base_link and a leg mounting link."""
    by_child = {joint.find("child").get("link"): joint for joint in root.findall("joint")}
    frame = np.eye(4)
    visited = set()
    while link_name != "base_link":
        if link_name in visited or link_name not in by_child:
            raise ValueError(f"Cannot resolve fixed mounting chain for {link_name}")
        visited.add(link_name)
        joint = by_child[link_name]
        if joint.get("type") != "fixed":
            raise ValueError(f"Leg mounting chain contains a moving joint: {joint.get('name')}")
        frame = transform(joint.find("origin")) @ frame
        link_name = joint.find("parent").get("link")
    return frame


def generate(urdf, output):
    root = ET.parse(urdf).getroot()
    origins, axes, geometry, hashes = [], [], {}, {}
    for leg in LEGS:
        frames, directions = [], []
        for index, part in enumerate(PARTS):
            joint = root.find(f"joint[@name='{leg}_{part}_joint']")
            parent = joint.find("parent").get("link")
            if (index > 0 and parent != f"{leg}_{PARTS[index-1]}") or joint.find("child").get(
                "link"
            ) != f"{leg}_{part}":
                raise ValueError("Guard expects a four-joint D1 leg chain")
            axis = np.fromstring(joint.find("axis").get("xyz"), sep=" ")
            if abs(np.linalg.norm(axis) - 1) > 1e-10:
                raise ValueError("Joint axis is not a unit vector")
            frame = transform(joint.find("origin"))
            if index == 0:
                frame = fixed_base_frame(root, parent) @ frame
            frames.append(frame)
            directions.append(axis)
            path = mesh_path(urdf, root, leg, part)
            hashes[str(path.relative_to(urdf.parent))] = hashlib.sha256(path.read_bytes()).hexdigest()
            geometry[leg, part] = link_vertices(urdf, root, leg, part)
        origins.append(frames)
        axes.append(directions)
    for front, rear in (("FL", "RL"), ("FR", "RR")):
        for part in PARTS:
            if not np.array_equal(geometry[front, part], geometry[rear, part]):
                raise ValueError("Front/rear local meshes differ; cannot share their envelope")

    def values(a):
        return ", ".join(f"{v:.16g}" for v in np.ravel(a))

    lines = [
        "// Generated by assets/d1/generate_geometry.py; do not edit by hand.",
        "// D1 joint frames, axes and visual-mesh envelopes.",
        "#pragma once",
        "namespace d1_side_guard_data {",
        "struct Vertex { double x, y, z; };",
        "struct Frame { double r[9]; double p[3]; };",
        f'inline constexpr char kUrdfSha256[] = "{hashlib.sha256(urdf.read_bytes()).hexdigest()}";',
    ]
    for path, digest in sorted(hashes.items()):
        lines.append(f"// {path} SHA256 {digest}")
    lines.append("inline constexpr Frame kOrigins[4][4] = {")
    for frames in origins:
        lines.append("  {")
        for frame in frames:
            lines.append("    {{" + values(frame[:3, :3]) + "}, {" + values(frame[:3, 3]) + "}},")
        lines.append("  },")
    lines.append("};")
    lines.append("inline constexpr Vertex kAxes[4][4] = {")
    for directions in axes:
        lines.append("  {" + ", ".join("{" + values(v) + "}" for v in directions) + "},")
    lines.append("};")
    for side, leg in (("Left", "FL"), ("Right", "FR")):
        for part in ("hip", "thigh", "calf"):
            vertices = geometry[leg, part]
            if part == "calf":
                low = np.floor(vertices.min(0) * 1e9) / 1e9
                high = np.ceil(vertices.max(0) * 1e9) / 1e9
                points = np.array(list(itertools.product(*zip(low, high))))
                suffix = "CalfBounds"
            else:
                points = trimesh.convex.convex_hull(vertices).vertices
                suffix = part.title()
            lines.append(f"inline constexpr Vertex k{side}{suffix}[] = {{")
            lines.extend("  {" + values(v) + "}," for v in points)
            lines.append("};")
        minimum, maximum, radius = wheel_bounds(geometry[leg, "foot"], axes[LEGS.index(leg)][3])
        for label, value in [("AxialMin", minimum), ("AxialMax", maximum), ("Radius", radius)]:
            lines.append(f"inline constexpr double k{side}Foot{label} = {value:.16g};")
    lines.append("}  // namespace d1_side_guard_data")
    output.write_text("\n".join(lines) + "\n")
    print(f"Generated {output} from {urdf}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--urdf", type=Path, default=DEFAULT_URDF)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    generate(args.urdf, args.output)
